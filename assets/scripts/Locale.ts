const DICT: Record<LocaleId, Pack> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en, ja, ko };
let active: LocaleId = 'zh-CN';
export const isLocale = (id: unknown): id is LocaleId => typeof id === 'string' && (LOCALES as readonly string[]).includes(id);
export function detectLocale(code?: string): LocaleId {
  const raw = (code || (typeof navigator !== 'undefined' ? navigator.language : '') || '').toLowerCase().replace(/_/g, '-');
  if (raw === 'chinese' || raw.startsWith('zh')) return /tw|hk|mo|hant/.test(raw) ? 'zh-TW' : 'zh-CN';
  if (raw === 'japanese' || raw.startsWith('ja')) return 'ja';
  if (raw === 'korean' || raw.startsWith('ko')) return 'ko';
  if (raw === 'english' || raw.startsWith('en')) return 'en';
  return 'zh-CN';
}
export function setActiveLocale(id: LocaleId) { active = id; }
export const activeLocale = () => active;
export function t(key: string, vars?: Record<string, string | number>): string {
  const text = DICT[active][key] ?? DICT['zh-CN'][key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] === undefined ? `{${name}}` : String(vars[name]));
}
/** Catalog names stay in Chinese until a crop.* / map.* key exists. */
export function tx(key: string, fallback: string) {
  return DICT[active][key] ?? DICT['zh-CN'][key] ?? fallback;
}
