export const SOIL_TEXT = {'zh-CN': zhCN, 'zh-TW': zhTW, en, ja, ko};
export type SoilTextKey = keyof typeof zhCN;

export function isLocale(value: unknown): value is LocaleId {
  return LOCALES.includes(value as LocaleId);
}

export function t(key: string, vars: Record<string, string | number> = {}, locale?: string): string {
  const id: LocaleId = isLocale(locale) ? locale : 'zh-CN';
  const table = SOIL_TEXT[id] as Record<string, string>;
  const raw = table[key] ?? (SOIL_TEXT['zh-CN'] as Record<string, string>)[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] === undefined ? `{${name}}` : String(vars[name]));
}

